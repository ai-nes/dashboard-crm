function buildPortfolioPoints(
  labels: string[],
  portfolioValues: number[],
  benchmarkValues: number[],
  prefix: string,
): PortfolioPerformancePoint[] {
  return labels.map((label, index) => ({
    id: `${prefix}-${index}`,
    label,
    timestamp: `2026-01-${String((index % 28) + 1).padStart(2, "0")}T00:00:00.000Z`,
    portfolio_value: { value: portfolioValues[index], currency_code: "USD" },
    benchmark_value: { value: benchmarkValues[index], currency_code: "USD" },
  }));
}

